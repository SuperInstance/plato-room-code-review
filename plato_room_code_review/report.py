"""
Review report generator for the PLATO Code Review Room.

Takes a list of CheckResult objects and produces a structured markdown report
with summary, per-check details, and an overall recommendation.
"""

from __future__ import annotations

from typing import Sequence

# Support both package-relative and standalone imports
try:
    from .reviewer import CheckResult
except ImportError:
    from reviewer import CheckResult


# Severity ordering for recommendations
_SEVERITY_WEIGHT = {"error": 3, "warning": 2, "info": 1}


def _recommendation(results: Sequence[CheckResult]) -> str:
    """Determine overall recommendation from check results."""
    failing = [r for r in results if not r.passed]
    if not failing:
        return "APPROVE"

    # Any failing check with severity "error" → REQUEST_CHANGES
    has_error = any(r.severity == "error" for r in failing)
    if has_error:
        return "REQUEST_CHANGES"

    return "COMMENT"


def _icon(result: CheckResult) -> str:
    """Status icon for a check result."""
    if result.passed:
        return "✅"
    if result.severity == "error":
        return "❌"
    if result.severity == "warning":
        return "⚠️"
    return "ℹ️"


def generate_report(
    results: Sequence[CheckResult],
    *,
    repo: str = "",
    pr_number: int | None = None,
    author: str = "",
) -> str:
    """Generate a full markdown review report.

    Args:
        results: List of CheckResult from run_all_checks().
        repo: Repository name (owner/repo) for the header.
        pr_number: PR number for the header.
        author: PR author for the header.

    Returns:
        Markdown-formatted report string.
    """
    total = len(results)
    passed = sum(1 for r in results if r.passed)
    failed = total - passed
    recommendation = _recommendation(results)

    lines: list[str] = []

    # ── Header ──────────────────────────────────────────────
    lines.append("## 🔍 PLATO Code Review Report\n")

    if repo or pr_number:
        header_parts = []
        if repo:
            header_parts.append(f"**Repo:** `{repo}`")
        if pr_number:
            header_parts.append(f"**PR:** #{pr_number}")
        if author:
            header_parts.append(f"**Author:** @{author}")
        lines.append(" | ".join(header_parts))
        lines.append("")

    # ── Summary ─────────────────────────────────────────────
    rec_icon = {"APPROVE": "✅", "REQUEST_CHANGES": "🚫", "COMMENT": "💬"}
    lines.append("### Summary\n")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Checks Run | {total} |")
    lines.append(f"| Passed | {passed} ✅ |")
    lines.append(f"| Failed | {failed} ❌ |")
    lines.append(f"| Recommendation | {rec_icon.get(recommendation, '💬')} **{recommendation}** |")
    lines.append("")

    # ── Details ─────────────────────────────────────────────
    lines.append("### Detailed Results\n")

    # Sort: failing first (by severity desc), then passing
    sorted_results = sorted(
        results,
        key=lambda r: (
            r.passed,  # failing (False=0) before passing (True=1)
            -_SEVERITY_WEIGHT.get(r.severity, 0),
        ),
    )

    for r in sorted_results:
        icon = _icon(r)
        lines.append(f"#### {icon} {r.name}")
        lines.append(f"\n- **Check ID:** `{r.check_id}`")
        lines.append(f"- **Status:** {'PASSED' if r.passed else 'FAILED'}")
        lines.append(f"- **Severity:** `{r.severity}`")
        lines.append(f"- **Message:** {r.message}")
        if r.file_hints:
            hint_list = ", ".join(f"`{h}`" for h in r.file_hints)
            lines.append(f"- **Files:** {hint_list}")
        lines.append("")

    # ── Footer ──────────────────────────────────────────────
    lines.append("---")
    lines.append(
        "_Generated by [PLATO Code Review Room]"
        "(https://github.com/SuperInstance/plato-room-code-review)_"
    )

    return "\n".join(lines)


def generate_short_summary(results: Sequence[CheckResult]) -> str:
    """Generate a one-line summary suitable for PR status checks.

    Example: "PLATO Review: 8/10 checks passed — APPROVE"
    """
    total = len(results)
    passed = sum(1 for r in results if r.passed)
    rec = _recommendation(results)
    return f"PLATO Review: {passed}/{total} checks passed — {rec}"
